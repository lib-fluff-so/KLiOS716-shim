#!/usr/bin/env python3
# Generates src/font.h: 8x16 bitmap font, ASCII 32..126, rendered from DejaVu Sans Mono.
import sys
from PIL import Image, ImageDraw, ImageFont
TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
font = ImageFont.truetype(TTF, 13)
rows = []
for c in range(32, 127):
    im = Image.new("1", (8, 16), 0)
    d = ImageDraw.Draw(im)
    d.text((0, 0), chr(c), font=font, fill=1)
    px = im.load()
    glyph = []
    for y in range(16):
        b = 0
        for x in range(8):
            if px[x, y]:
                b |= 0x80 >> x
        glyph.append(b)
    rows.append(glyph)
with open("src/font.h", "w") as f:
    f.write("/* generated by tools/genfont.py (DejaVu Sans Mono, 8x16, ASCII 32..126) */\n")
    f.write("static const unsigned char font8x16[95][16] = {\n")
    for i, g in enumerate(rows):
        f.write("    {" + ",".join("0x%02x" % b for b in g) + "}, /* '%s' */\n" % (chr(32 + i) if chr(32 + i) not in "\\*/" else "?"))
    f.write("};\n")
print("ok", len(rows))
